-- Existing production rows belong to the single-user installation.
create table if not exists public.indai_memory (
  id bigint generated by default as identity primary key, kind text not null default 'fact',
  text text not null, created_at timestamptz not null default now()
);
alter table public.indai_memory add column if not exists user_id uuid not null default '00000000-0000-4000-8000-000000000001',
  add column if not exists uses integer not null default 0, add column if not exists last_used timestamptz;
alter table public.indai_memory alter column kind set default 'fact';
-- The existing memory table was empty at rollout. No legacy rows are rewritten.
alter table public.indai_memory add constraint indai_memory_kind check (kind in ('fact','preference','rule','vocabulary'));
create index indai_memory_rank on public.indai_memory(user_id,uses desc,last_used desc,created_at desc);
alter table public.indai_memory enable row level security;
revoke all on public.indai_memory from public,anon,authenticated;
grant all on public.indai_memory to service_role;

create function public.indai_learn(p_user uuid,p_items jsonb) returns setof public.indai_memory
language plpgsql set search_path='' as $$
declare item jsonb; cleaned text;
begin
  perform pg_advisory_xact_lock(hashtextextended(p_user::text,5));
  for item in select value from jsonb_array_elements(p_items) limit 6 loop
    cleaned := left(btrim(regexp_replace(item->>'text','\s+',' ','g')),300);
    if length(cleaned)>3 and not exists(select 1 from public.indai_memory where user_id=p_user and lower(text)=lower(cleaned)) then
      return query insert into public.indai_memory(user_id,kind,text)
        values(p_user,case when item->>'kind' in ('preference','rule','vocabulary') then item->>'kind' else 'fact' end,cleaned) returning *;
    end if;
  end loop;
end $$;
create function public.indai_use_memories(p_user uuid,p_ids bigint[]) returns void language sql set search_path='' as $$
  update public.indai_memory set uses=uses+1,last_used=now() where user_id=p_user and id=any(p_ids)
$$;
create function public.indai_memory_owners(p_after uuid default null) returns table(user_id uuid)
language sql stable set search_path='' as $$
  select distinct m.user_id from public.indai_memory m where p_after is null or m.user_id>p_after order by m.user_id limit 100
$$;
revoke all on function public.indai_learn(uuid,jsonb),public.indai_use_memories(uuid,bigint[]),public.indai_memory_owners(uuid) from public,anon,authenticated;
grant execute on function public.indai_learn(uuid,jsonb),public.indai_use_memories(uuid,bigint[]),public.indai_memory_owners(uuid) to service_role;
